<ul>
<li><strong>Flap</strong> — 잇몸을 열어 뼈 상태를 정확히 확인</li>
<li><strong>Bone Graft</strong> — 부족한 부위를 골이식으로 보강</li>
<li><strong>Membrane</strong> — 필요 시 차폐막으로 안정적인 뼈 재생 유도</li>
