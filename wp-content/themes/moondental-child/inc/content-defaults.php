<h3>6. 부분 틀니 (Partial Denture)</h3>
<p>일부 치아가 결손된 경우, 남아 있는 치아(지대치)에 유지장치를 걸어 사용하는 가철성 보철물. 빠진 치아만 메우는 착탈식 틀니입니다.</p>

<h4>종류</h4>
<ul>
<li><strong>레진 부분틀니 (임시 틀니)</strong> — 플라스틱 소재, 저렴하지만 두껍고 내구성 약함</li>
<li><strong>코발트크롬 합금 틀니(금속 틀니)</strong> — 얇고 튼튼, 이물감 적음, 가장 표준적</li>
<li><strong>플렉서블 틀니</strong> — 가볍고 탄력 있는 소재, 심미성 좋고 금속 고리 없음, 수리 어렵고 내구성 떨어질 수 있음</li>
</ul>

<h4>장점</h4>
<ul>
<li>비용 저렴 — 브릿지·임플란트보다 경제적</li>
<li>여러 치아 상실 시 효율적</li>
<li>수리·재제작 용이 — 치아 추가 상실 시 보완 가능</li>
<li>수술 필요 없음 — 고령자·전신질환 환자도 가능</li>
</ul>

<h4>단점</h4>
<ul>
<li>이물감 — 금속 구조물·큰 베이스로 말하기·씹기 다소 불편</li>
<li>심미성 떨어짐 — 금속 클라스프가 보일 수 있음 (특히 앞니)</li>
<li>저작력 제한 — 자연치·고정성 보철보다 약함</li>
<li>뼈 흡수 진행 — 치근 없는 부위는 시간 지나며 치조골 흡수</li>
<li>정기 유지관리 필요 — 위생 관리·점검 중요</li>
</ul>
<p><strong>유지 관리</strong>: 하루 1회 이상 전용 의치세정제 사용, 잘 때는 빼놓고 보관, 정기 내원으로 안정성·점막 상태·남은 치아 상태 점검, <strong>남아 있는 자연치아 우식·치주 관리가 매우 중요</strong>.</p>

<h3>7. 치아 미백 (Whitening)</h3>
<p>치아 색조를 개선해 밝고 하얗게 만드는 술식. 크게 세 가지 방식이 있습니다.</p>

<h4>(1) 치과 내 전문 미백 (Office Whitening)</h4>
<ul>
<li><strong>방법</strong>: 고농도 과산화수소 제제를 치아 표면에 도포 후 광조사(레이저·LED)로 활성화</li>
<li><strong>장점</strong>: 짧은 시간(1~2회 방문) 안에 빠른 효과</li>
<li><strong>단점</strong>: 시술 직후 시린 증상(지각과민) 가능, 유지기간 개인차</li>
</ul>

<h4>(2) 가정 미백 (Home Whitening)</h4>
<ul>
<li><strong>방법</strong>: 치과에서 개인 맞춤 트레이 제작 → 저농도 미백제(과산화카바마이드 등)를 트레이에 넣어 일정 시간 착용</li>
<li><strong>장점</strong>: 점진적·자연스러운 미백, 원하는 만큼 조절 가능</li>
<li><strong>단점</strong>: 2주 이상 꾸준히 착용해야 효과, 환자 협조도 중요</li>
</ul>

<h4>(3) 복합 미백 (Combined Whitening)</h4>
<p>치과 내 전문 미백 + 가정 미백 병행 → 가장 효과적이고 지속력이 좋은 방식.</p>

<h4>미백 치료의 특징</h4>
<ul>
<li><strong>영구적이지 않음</strong> — 음식·음주·흡연 습관에 따라 6개월~2년 후 재착색</li>
<li><strong>금기사항</strong> — 임산부·수유부, 미성숙 영구치, 심한 치경부 마모·우식, 알레르기 환자</li>
<li><strong>효과가 잘 안 나는 경우</strong> — 테트라사이클린 착색, 불소증, 금속·레진·세라믹 보철물(인공재료는 색이 변하지 않음)</li>
</ul>

<h4>시술 전후 주의사항</h4>
<ul>
<li><strong>시술 전</strong>: 스케일링·우식·충치 치료 선행</li>
<li><strong>시술 후 48시간</strong>: 색소 침착 음식 자제 (커피·홍차·와인·카레·김치·콜라 등)</li>
<li>지각과민이 심하면 불소 도포·시간 간격 조정</li>
</ul>

<h3>치료 기간 요약</h3>
<ul>
<li>치아 미백: 1~2회 내원 (전문가 미백 기준)</li>
<li>라미네이트: 2~3주 (2회 내원)</li>
<li>올세라믹 크라운: 1~2주 (1~2회 내원)</li>
<li>앞니 브릿지: 1~2주 (1~2회 내원)</li>
<li>임플란트 틀니: 식립 후 2~4개월</li>
<li>전체 틀니: 1~2개월</li>
<li>부분 틀니: 2~3주</li>
<li>전악 보철: 수개월~1년 이상</li>
</ul>

