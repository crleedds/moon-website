/** 현재 백과사전 글(또는 지정한 글)의 보강 데이터 · 없으면 null */
function moondental_enc_boost( $post = null ) {
	$post = $post ? get_post( $post ) : get_post();
	if ( ! $post || 'md_term' !== $post->post_type ) return null;
	$slug = urldecode( (string) $post->post_name );
	$map  = moondental_enc_boost_map();
	return isset( $map[ $slug ] ) ? $map[ $slug ] : null;
}

/** 보강 FAQ + 본문에서 만든 FAQ (중복 제거 · 최대 8) */
function moondental_enc_boost_faqs( $post, $generated ) {
	$b    = moondental_enc_boost( $post );
	$out  = array();
	$seen = array();
	foreach ( ( $b['faq'] ?? array() ) as $f ) { $out[] = $f; $seen[ mb_substr( $f[0], 0, 12 ) ] = 1; }
	foreach ( (array) $generated as $f ) {
		if ( empty( $f[0] ) || empty( $f[1] ) ) continue;
		$k = mb_substr( $f[0], 0, 12 );
		if ( isset( $seen[ $k ] ) ) continue;
		$out[] = $f; $seen[ $k ] = 1;
		if ( count( $out ) >= 8 ) break;
	}
	return $out;
}
